#include <bits/stdc++.h>
using namespace std;

int main(){
  int N, M;

  cout << "Enter two numbers N & M: ";
  cin >> N >> M;

  cout << N << " + " << M << " = " << (N + M) << endl;
  cout << N << " - " << M << " = " << (N - M) << endl;
  cout << N << " * " << M << " = " << (N * M) << endl;
  cout << N << " / " << M << " = " << (N / M) << endl;
  cout << N << " % " << M << " = " << (N % M) << endl;
}